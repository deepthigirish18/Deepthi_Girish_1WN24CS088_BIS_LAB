import numpy as np

def fitness(x):
    return sum(xi ** 2 for xi in x)

# Input
n = int(input("Enter number of wolves: "))
dim = int(input("Enter number of dimensions: "))
iterations = int(input("Enter number of iterations: "))

lb = float(input("Enter lower bound: "))
ub = float(input("Enter upper bound: "))

# Initialize wolf population
wolves = np.random.uniform(lb, ub, (n, dim))

alpha = np.zeros(dim)
beta = np.zeros(dim)
delta = np.zeros(dim)

alpha_score = float('inf')
beta_score = float('inf')
delta_score = float('inf')

# Main GWO loop
for t in range(iterations):

    # Evaluate fitness
    for i in range(n):
        wolves[i] = np.clip(wolves[i], lb, ub)
        score = fitness(wolves[i])

        if score < alpha_score:
            delta_score = beta_score
            delta = beta.copy()

            beta_score = alpha_score
            beta = alpha.copy()

            alpha_score = score
            alpha = wolves[i].copy()

        elif score < beta_score:
            delta_score = beta_score
            delta = beta.copy()

            beta_score = score
            beta = wolves[i].copy()

        elif score < delta_score:
            delta_score = score
            delta = wolves[i].copy()

    # Update wolf positions
    a = 2 - t * (2 / iterations)

    for i in range(n):
        for j in range(dim):

            r1, r2 = np.random.random(), np.random.random()
            A1 = 2 * a * r1 - a
            C1 = 2 * r2
            D_alpha = abs(C1 * alpha[j] - wolves[i][j])
            X1 = alpha[j] - A1 * D_alpha

            r1, r2 = np.random.random(), np.random.random()
            A2 = 2 * a * r1 - a
            C2 = 2 * r2
            D_beta = abs(C2 * beta[j] - wolves[i][j])
            X2 = beta[j] - A2 * D_beta

            r1, r2 = np.random.random(), np.random.random()
            A3 = 2 * a * r1 - a
            C3 = 2 * r2
            D_delta = abs(C3 * delta[j] - wolves[i][j])
            X3 = delta[j] - A3 * D_delta

            wolves[i][j] = (X1 + X2 + X3) / 3

# Output
print("\nBest Solution:", alpha)
print("Best Fitness:", alpha_score)
print("Optimization Completed!")