import random

# Input hospital resources
beds = int(input("Enter available beds: "))
doctors = int(input("Enter available doctors: "))
nurses = int(input("Enter available nurses: "))
equipment = int(input("Enter available equipment: "))

n = int(input("Enter number of patients: "))

patients = []

for i in range(n):
    print("\nEnter details for Patient", i + 1)

    priority = int(input("Priority (1=High, 2=Medium, 3=Low): "))
    doc = int(input("Doctors required: "))
    nurse = int(input("Nurses required: "))
    equip = int(input("Equipment required: "))

    patients.append((i + 1, priority, doc, nurse, equip))


def evaluate(order):
    cost = 0
    time_slot = 0

    bed_used = 0
    doc_used = 0
    nurse_used = 0
    equip_used = 0

    schedule = []

    for idx in order:
        pid, priority, doc, nurse, equip = patients[idx]

        if (bed_used + 1 > beds or
            doc_used + doc > doctors or
            nurse_used + nurse > nurses or
            equip_used + equip > equipment):

            time_slot += 1
            bed_used = 0
            doc_used = 0
            nurse_used = 0
            equip_used = 0

        bed_used += 1
        doc_used += doc
        nurse_used += nurse
        equip_used += equip

        waiting_cost = priority * time_slot
        resource_cost = doc + nurse + equip

        cost += waiting_cost + resource_cost

        schedule.append((pid, priority, time_slot + 1))

    return cost, schedule


def cuckoo_search():
    nests = [
        random.sample(range(len(patients)), len(patients))
        for _ in range(10)
    ]

    best = nests[0]
    best_cost = evaluate(best)[0]

    for _ in range(100):
        for i in range(len(nests)):
            new_nest = nests[i][:]

            a, b = random.sample(range(len(patients)), 2)
            new_nest[a], new_nest[b] = new_nest[b], new_nest[a]

            new_cost = evaluate(new_nest)[0]

            if new_cost < evaluate(nests[i])[0]:
                nests[i] = new_nest

            if new_cost < best_cost:
                best = new_nest[:]
                best_cost = new_cost

        # Abandon worst nest
        worst = max(nests, key=lambda x: evaluate(x)[0])

        nests[nests.index(worst)] = random.sample(
            range(len(patients)), len(patients)
        )

    return best, best_cost


best, cost = cuckoo_search()

cost, schedule = evaluate(best)

print("\n--- Optimized Hospital Allocation ---")

for pid, priority, slot in schedule:
    print("Patient:", pid,
          "| Priority:", priority,
          "| Time Slot:", slot)

print("\nMinimum Allocation Cost:", cost)